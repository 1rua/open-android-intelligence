package com.openandroidintelligence.mobile.onboarding

/**
 * 一项权限在**当前设备上的真实授权状态**。
 *
 * 状态刻意分得比「已授权 / 未授权」更细，因为三种"没授权"对用户意味着完全不同的下一步：
 *
 * 1. 从未申请过（[UNKNOWN]）——点按钮就会弹出系统授权框，属于正常流程；
 * 2. 申请后被拒绝，但系统仍允许再次询问（[DENIED]）——可以再点一次，仍会弹框；
 * 3. 已被永久拒绝（[BLOCKED]）——系统不会再弹任何对话框，**唯一出口是应用详情页**。
 *
 * 把 3 混进 2 会造成需求明令禁止的「重复弹窗」：用户点了「开启」却什么都没发生，
 * 只能反复点击。因此界面必须据 [BLOCKED] 把按钮文案改成「前往设置」。
 *
 * [NOT_REQUIRED] 用于**没有可持久查询授权状态**的权限：屏幕采集每次使用时都由系统
 * 投屏确认框现场询问，既不存在"已授权"，也不该被渲染成"未授权"（那会让用户以为
 * 现在必须做点什么）。
 */
enum class PermissionStatus {
    /** 尚未查询到结果（页面刚进入、状态未回填时）。 */
    UNKNOWN,

    /** 已授权：权限可被真实使用。 */
    GRANTED,

    /** 未授权，但系统仍允许再次弹出授权框。 */
    DENIED,

    /** 已被永久拒绝：系统不再弹框，只能引导用户去系统设置手动开启。 */
    BLOCKED,

    /**
     * 无需持久授权：例如屏幕采集由系统在每次使用时现场确认，
     * 或该权限在当前 Android 版本上根本不存在。
     */
    NOT_REQUIRED,
    ;
}
